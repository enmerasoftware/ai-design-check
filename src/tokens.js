/**
 * Writes a design system (src/system.js) for each platform: CSS variables with a dark theme, a Tailwind v4 @theme,
 * JSON tokens, a SwiftUI file (colors for light and dark, fonts that follow Dynamic Type) and a Jetpack Compose file
 * (color schemes and Typography), plus an HTML preview page that shows every role in both themes.
 */

const kebab = (name) => name.replace(/([A-Z])/g, '-$1').toLowerCase();
const camel = (name) => name.replace(/-([a-z])/g, (_, char) => char.toUpperCase());
const flat = (colors) => Object.entries(colors).flatMap(([name, value]) => (Array.isArray(value) ? value.map((item, index) => [`${name}${index + 1}`, item]) : [[name, value]]));
const stack = (name, category) => `"${name}", ${category === 'serif' ? 'Georgia, serif' : category === 'mono' ? 'ui-monospace, monospace' : 'system-ui, sans-serif'}`;
const googleUrl = (system) => {
    const names = [...new Set([system.fonts.ui, system.fonts.display, system.fonts.numeric, system.fonts.mono])].filter((name) => system.fonts.sources[name] === 'google');

    return names.length ? `https://fonts.googleapis.com/css2?${names.map((name) => `family=${name.replace(/ /g, '+')}:wght@400;500;600;700`).join('&')}&display=swap` : null;
};

export function css(system) {
    const colors = (theme) => flat(theme).map(([name, value]) => `    --color-${kebab(name)}: ${value};`).join('\n');
    const type = Object.entries(system.type).map(([role, item]) => [
        `    --text-${role}: ${item.size / 16}rem;`,
        `    --text-${role}--line-height: ${item.lineHeight};`,
        `    --text-${role}--letter-spacing: ${item.letterSpacing}em;`,
        `    --text-${role}--font-weight: ${item.weight};`,
    ].join('\n')).join('\n');
    const radius = Object.entries(system.shape.radius).map(([name, value]) => `    --radius-${name}: ${value}px;`).join('\n');
    const families = [['ui', system.fonts.ui], ['display', system.fonts.display], ['numeric', system.fonts.numeric], ['mono', system.fonts.mono]].map(([role, name]) => `    --font-${role}: ${stack(name, system.fonts.categories[name])};`).join('\n');

    return `/* ${system.character} · ${system.kind} · brand ${system.brand}. Generated by @enmera/ai-design-check system. */
${googleUrl(system) ? `@import url("${googleUrl(system)}");\n` : ''}
:root {
${families}
${type}
${radius}
${colors(system.color.light)}
    color-scheme: light;
}

@media (prefers-color-scheme: dark) {
    :root:not([data-theme="light"]) {
${colors(system.color.dark).replace(/^ {4}/gm, '        ')}
        color-scheme: dark;
    }
}

:root[data-theme="dark"] {
${colors(system.color.dark)}
    color-scheme: dark;
}

body { background: var(--color-bg); color: var(--color-text); font-family: var(--font-ui); }
.tabular { font-variant-numeric: tabular-nums; }
`;
}

/** Tailwind v4: the same variables inside @theme, so bg-surface, text-text-secondary, text-body, rounded-md work. */
export function tailwind(system) {
    return css(system).replace(':root {', '@theme {').replace('body {', '@layer base {\n    body {').replace(/\.tabular \{[^}]*\}\n$/, '}\n');
}

export const json = (system) => `${JSON.stringify(system, null, 2)}\n`;

export function swift(system) {
    const color = (name) => {
        const [light, dark] = [system.color.light[name], system.color.dark[name]];

        return `    static let ${name} = Color(light: 0x${light.slice(1)}, dark: 0x${dark.slice(1)})`;
    };
    const names = Object.keys(system.color.light).filter((name) => !Array.isArray(system.color.light[name]));
    const font = (role, item) => {
        return `    static let ${role} = Font.custom("${item.font}", size: ${item.size}, relativeTo: .${item.ios}).weight(.${{ 400: 'regular', 500: 'medium', 600: 'semibold', 700: 'bold' }[item.weight]})${item.tabular ? '.monospacedDigit()' : ''}`;
    };

    return `// ${system.character} · ${system.kind} · brand ${system.brand}. Generated by @enmera/ai-design-check system.
// Fonts: add the font files to the app target and list them under UIAppFonts in Info.plist (Google Fonts are OFL, free to bundle).
// Sizes use relativeTo, so text follows Dynamic Type. Tracking: DSType.tracking(for:) in points.
import SwiftUI

enum DSColor {
${names.map(color).join('\n')}
}

enum DSType {
${Object.entries(system.type).map(([role, item]) => font(role, item)).join('\n')}

    /// Letter-spacing in points for a role (the CSS em value times the size).
    static func tracking(for role: String) -> CGFloat {
        switch role {
${Object.entries(system.type).map(([role, item]) => `        case "${role}": return ${(item.letterSpacing * item.size).toFixed(2)}`).join('\n')}
        default: return 0
        }
    }
}

enum DSSpace {
${system.shape.space.filter((value) => value > 0).map((value) => `    static let s${value}: CGFloat = ${value}`).join('\n')}
}

enum DSRadius {
${Object.entries(system.shape.radius).map(([name, value]) => `    static let ${name}: CGFloat = ${value}`).join('\n')}
}

extension Color {
    /// A color that follows the light and dark appearance.
    init(light: UInt32, dark: UInt32) {
        self.init(UIColor { traits in
            let hex = traits.userInterfaceStyle == .dark ? dark : light
            return UIColor(red: CGFloat((hex >> 16) & 0xFF) / 255, green: CGFloat((hex >> 8) & 0xFF) / 255, blue: CGFloat(hex & 0xFF) / 255, alpha: 1)
        })
    }
}
`;
}

export function kotlin(system) {
    const scheme = (theme, dark) => `val ${dark ? 'Dark' : 'Light'}Colors = ${dark ? 'darkColorScheme' : 'lightColorScheme'}(
    primary = Color(0xFF${theme.accent.slice(1)}),
    onPrimary = Color(0xFF${theme.accentInk.slice(1)}),
    primaryContainer = Color(0xFF${theme.accentSoft.slice(1)}),
    onPrimaryContainer = Color(0xFF${theme.accentText.slice(1)}),
    background = Color(0xFF${theme.bg.slice(1)}),
    onBackground = Color(0xFF${theme.text.slice(1)}),
    surface = Color(0xFF${theme.surface.slice(1)}),
    onSurface = Color(0xFF${theme.text.slice(1)}),
    surfaceVariant = Color(0xFF${theme.subtle.slice(1)}),
    onSurfaceVariant = Color(0xFF${theme.textSecondary.slice(1)}),
    outline = Color(0xFF${theme.borderStrong.slice(1)}),
    outlineVariant = Color(0xFF${theme.border.slice(1)}),
    error = Color(0xFF${theme.danger.slice(1)}),
    onError = Color(0xFF${theme.dangerInk.slice(1)}),
)`;
    const family = (name) => `${camel(name.toLowerCase().replace(/ /g, '-'))}Family`;
    const families = [...new Set(Object.values(system.type).map((item) => item.font))];

    return `// ${system.character} · ${system.kind} · brand ${system.brand}. Generated by @enmera/ai-design-check system.
// Fonts: put the font files in res/font (Google Fonts are OFL, free to bundle) and fill in the FontFamily lines.
package design

import androidx.compose.material3.Typography
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.em
import androidx.compose.ui.unit.sp

${families.map((name) => `val ${family(name)}: FontFamily = FontFamily.Default // ${name}: FontFamily(Font(R.font.${name.toLowerCase().replace(/ /g, '_')}_regular), …)`).join('\n')}

${scheme(system.color.light, false)}

${scheme(system.color.dark, true)}

val AppTypography = Typography(
${Object.entries(system.type).filter(([role]) => role !== 'stat').map(([, item]) => `    ${item.android} = TextStyle(fontFamily = ${family(item.font)}, fontSize = ${item.size}.sp, lineHeight = ${Math.round(item.size * item.lineHeight)}.sp, letterSpacing = ${item.letterSpacing}.em, fontWeight = FontWeight.W${item.weight}),`).join('\n')}
)

object Radius {
${Object.entries(system.shape.radius).map(([name, value]) => `    val ${name} = ${value}.dp`).join('\n')}
}

object Space {
${system.shape.space.filter((value) => value > 0).map((value) => `    val s${value} = ${value}.dp`).join('\n')}
}
`;
}
